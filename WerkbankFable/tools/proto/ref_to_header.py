"""ref_bands.json (from make_reference.py) -> test/ref_data.h for the C++ tests.
Run: python3 tools/proto/make_reference.py /tmp/ref && python3 tools/proto/ref_to_header.py /tmp/ref/ref_bands.json"""
import json, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'ref_out', 'ref_bands.json')
d = json.load(open(src))
cases = d['cases']
o = ["// Generated by tools/proto/ref_to_header.py from ref_bands.json. Do not edit by hand.", "#pragma once",
     "static const int REF_NB = %d;" % len(d['centres']),
     "static const double REF_CENTRES[%d] = {%s};" % (len(d['centres']), ", ".join(str(c) for c in d['centres'])),
     "struct RefCase { const char* name; double seconds, rmsDb; double bands[%d]; };" % len(d['centres']),
     "static const int REF_NCASES = %d;" % len(cases),
     "static const RefCase REF_CASES[%d] = {" % len(cases)]
for k, v in cases.items():
    o.append('\t{"%s", %r, %r, {%s}},' % (k, v['seconds'], v['rms_db'], ", ".join(repr(b) for b in v['bands'])))
o.append("};")
open(os.path.join(HERE, '..', '..', 'test', 'ref_data.h'), 'w').write("\n".join(o) + "\n")
print(len(cases), 'cases')
