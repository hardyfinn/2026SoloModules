def values(row):
    name, mode, tune, voices, spread, rub, rule, cad, slide, shake, whoop, loose = row
    k, unit = rub_knob(rub)
    assert -1e-9 <= k <= 1 + 1e-9, (name, rub)
    chance_mode = 0 if rule == "RULE" else 1
    chance = 0.5 if rule == "RULE" else float(rule)
    return dict(ROOT=0, OCT=0, MODE=MODES.index(mode), TUNE=tune, VOICES=voices, SPREAD=spread, RUB=min(1, max(0, k)),
                UNIT=unit, WHEN=chance_mode, CHANCE=chance, CADENCE=1 if cad == "RESOLVE" else 0,
                SLIDE=slide, SHAKE=shake, WHOOP=whoop, LOOSE=loose)

if __name__ == "__main__":
    outdir = os.path.join(ROOT, "presets", "Bulgaria")
    os.makedirs(outdir, exist_ok=True)
    for f in os.listdir(outdir):
        if f.endswith(".vcvm"): os.remove(os.path.join(outdir, f))
    lines = ["# name " + " ".join(IDS)]
    for i, row in enumerate(P):
        v = values(row)
        doc = {"plugin": "BulgariaFable", "model": "Bulgaria", "version": "2.0.0",
               "params": [{"value": round(float(v[n]), 6), "id": j} for j, n in enumerate(IDS)],
               "data": {"seed": "%016x" % (0xB0A000 + i)}}
        json.dump(doc, open(os.path.join(outdir, "%02d_%s.vcvm" % (i + 1, row[0])), "w"), indent=1)
        lines.append(row[0].replace(" ", "_") + " " + " ".join("%.6f" % float(v[n]) for n in IDS))
    os.makedirs(os.path.join(ROOT, "test"), exist_ok=True)
    open(os.path.join(ROOT, "test", "presets.txt"), "w").write("\n".join(lines) + "\n")
    v = values(P[0])
    hdr = "// Generated by tools/make_presets.py: the Init values, in ParamIds order.\n#pragma once\nstatic const float BG_DEFAULTS[%d] = {%s};\n" % (
        len(IDS), ", ".join("%.6ff" % float(v[n]) for n in IDS))
    open(os.path.join(ROOT, "src", "defaults.hpp"), "w").write(hdr)
    print("wrote", len(P), "presets")
