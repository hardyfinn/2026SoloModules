#!/usr/bin/env python3
# Writes presets/Bulgaria/NN_Name.vcvm, test/presets.txt (the same settings as param values, for the demo tool)
# and src/defaults.hpp (the Init values the module's params default to).
# Values are the table in docs/BUILD-INSTRUCTIONS.md section 8; RUB is given as cents ("170c") or Hz ("30hz").
import os, json
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

MODES = ["SHOPE", "AEOLIAN", "DORIAN", "PHRYGIAN", "HIJAZ", "MIXOLYDIAN", "MAJOR"]
# Param order = the module's ParamIds enum.
IDS = ["ROOT", "OCT", "MODE", "TUNE", "VOICES", "SPREAD", "RUB", "UNIT", "WHEN", "CHANCE", "CADENCE", "SLIDE", "SHAKE", "WHOOP", "LOOSE"]

def rub_knob(s):
    if s.endswith("hz"): return ((float(s[:-2]) - 1.0) / 79.0) ** (1 / 2.2), 1
    return (float(s[:-1]) - 25.0) / 225.0, 0

