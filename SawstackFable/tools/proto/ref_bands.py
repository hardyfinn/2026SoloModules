"""Writes test/ref_bands.h for the C++ agreement test (make test, check 8), and the unit numbers for check 1.
Band measure (same as bandLevels() in test/render.cpp): mono (L+R)/2 of the normalised output,
Hann-windowed 8192-point periodograms with hop 4096, averaged, summed into third-octave bands
centred on 1000*2^(k/3), k = -13..12 (50 Hz to 16 kHz)."""
import os, sys, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import sawstack_ref as R
SR = R.SR; SECONDS = 10.0; N = int(SR * SECONDS)
KS = list(range(-13, 13))

def bands(x):
    n = 8192; hop = 4096; w = np.hanning(n + 1)[:-1]
    P = np.zeros(n // 2 + 1); cnt = 0
    for s in range(0, len(x) - n + 1, hop):
        P += np.abs(np.fft.rfft(x[s:s + n] * w)) ** 2; cnt += 1
    P /= cnt; f = np.arange(n // 2 + 1) * SR / n
    out = []
    for k in KS:
        c = 1000 * 2 ** (k / 3); lo, hi = c * 2 ** (-1 / 6), c * 2 ** (1 / 6)
        m = (f >= lo) & (f < hi); out.append(10 * np.log10(P[m].sum() + 1e-20))
    return out

def bass_controls():
    notes = [-24, None, -24, -12, -24, None, -21, -24, -24, None, -24, -12, -17, None, -19, -14]
    step = 0.121; p = np.zeros(N); g = np.zeros(N); last = 0.0; i = 0
    while True:
        a = int(i * step * SR); b = int((i + 1) * step * SR)
        if a >= N: break
        nt = notes[i % 16]
        if nt is not None: last = nt / 12.0; g[a:min(N, a + int((b - a) * 0.55))] = 10.0
        p[a:] = last; i += 1
    return p, g

# name, pitch, spread, timbre, rich, seed   (AGE 0.6, DRIVE 0.35, Octaves, stereo)
SCENES = [('unison saw', -1.0, 0.0, 1.0, 0.0, 3), ('octave stack sines', 0.0, 1.0, 0.0, 0.0, 4),
          ('richness 0.7', -2.0, 0.2, 1.0, 0.7, 6), ('timbre 0.5 swarm', -1.0, 0.28, 0.5, 0.0, 5)]

def scene_bands(noise):
    rows = []
    for nm, pi, sp, tb, rc, sd in SCENES:
        y = R.render(np.full(N, pi), sp, tb, rc, np.ones(N), age=0.6, drive=0.35, seed=sd, noise=noise)
        b = bands(y.mean(1)); rows.append((nm, b)); print(nm, ' '.join('%.1f' % v for v in b))
    p, g = bass_controls(); ea = 0.6 if noise else 0.0
    e2, _ = R.envelope(g, 0.002, 0.16, ea, 1); e1, _ = R.envelope(g, 0.002, 0.11, ea, 2)
    y = R.render(p, 0.26, 1.0, 0.1 + 0.6 * e1, e2, age=0.6, drive=0.35, seed=7, noise=noise)
    b = bands(y.mean(1)); rows.append(('bass line', b)); print('bass line', ' '.join('%.1f' % v for v in b))
    return rows

def table(name, rows):
    return ('static const RefBands %s[] = {\n' % name +
            '\n'.join('\t{"%s", {%s}},' % (nm, ', '.join('%.3f' % v for v in b)) for nm, b in rows) + '\n};\n')

if __name__ == '__main__':
    det = scene_bands(False); noisy = scene_bands(True)
    units = []
    for sd in (1, 2, 12345):
        u = R.make_unit(sd)
        vals = [u[k][i] for i in range(5) for k in ('tune', 'vtrack', 'strack', 'shp', 'dc', 'lvl_db', 'lp_hz', 'droop', 'ph0')]
        units.append('\t{%dULL, {%s}},' % (sd, ', '.join('%.17g' % v for v in vals)))
    open(os.path.join(HERE, '..', '..', 'test', 'ref_bands.h'), 'w').write(
        '// Generated by tools/proto/ref_bands.py.  Do not edit.\n#pragma once\n'
        'static const int REF_K0 = %d, REF_NB = %d;\n' % (KS[0], len(KS)) +
        'struct RefBands { const char* name; double db[%d]; };\n' % len(KS) +
        table('REF_BANDS_DET', det) + table('REF_BANDS', noisy) +
        'static const int NUM_REF_BANDS = %d;\n' % len(det) +
        '// per oscillator i: tune, vtrack, strack, shp, dc, lvl_db, lp_hz, droop, ph0\n'
        'struct RefUnit { unsigned long long seed; double v[45]; };\nstatic const RefUnit REF_UNITS[] = {\n' + '\n'.join(units) + '\n};\n')
