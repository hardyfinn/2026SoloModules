"""Writes test/ref_data.h: the reference engine's measurements, for the C++ tests. python3 export_ref.py OUT.h"""
import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from tape_ref import *
MACH = ['4TR', '4TR HI', '4TR C', '8TR CASS', '8TR 7.5', '8TR 15', 'DECK', 'BOOMBOX', '1/4 INCH']
F = (40, 100, 1000, 5000, 10000, 14000); LV = (-20, 0, 6)
out = ['// Generated by tools/proto/export_ref.py from tape_ref.py. Do not edit.', '#pragma once']
def arr(name, vals): out.append('static const double %s[] = {%s};' % (name, ', '.join('%.17g' % v for v in np.ravel(vals))))
for fs in (44100, 48000, 96000):
    t = np.arange(fs * 2) / fs
    def lvl(y, f):
        w = np.hanning(len(y)); return 2 * abs(np.sum(y * w * np.exp(-2j * np.pi * f * np.arange(len(y)) / fs))) / np.sum(w)
    def g(y, f, L): return 20 * np.log10(lvl(y[fs // 2:, 0], f) / db(L))
    def resp(name, L, fl=F, **kw): return [g(deck(db(L) * np.sin(2 * np.pi * f * t)[:, None], fs, name, quiet=True, **kw), f, L) for f in fl]
    kw0 = dict(age=0.0)
    arr('RESP_%d' % fs, [[resp(m, L, **kw0) for L in LV] for m in MACH])
    arr('RESP_S05_%d' % fs, [resp('4TR', L, age=0.0, strength=0.5) for L in LV])
    arr('RESP_S0_%d' % fs, [resp(m, 6, age=0.0, strength=0.0) for m in MACH])
    hd = []
    for name, tp in (('4TR', 'I'), ('4TR', 'II'), ('4TR', 'IV'), ('8TR 15', 'II')):
        mol = (TAPES_REEL if MACHINES[name]['reel'] else TAPES_CASS)[tp]['mol']
        for dl in (0, -10):
            y = deck(db(mol + dl) * np.sin(2 * np.pi * 315 * t)[:, None], fs, name, tape=tp, quiet=True, age=0)[fs // 2:, 0]
            hd.append(100 * lvl(y, 945) / lvl(y, 315))
    arr('HD3_%d' % fs, hd)
    bb = []
    for b in (-1, 0, 1):
        bb += [g(deck(db(-30) * np.sin(2 * np.pi * 315 * t)[:, None], fs, '4TR', quiet=True, age=0, bias=b), 315, -30), resp('4TR', -20, (10000,), age=0, bias=b)[0]]
    arr('BIAS_%d' % fs, bb)
    arr('AZ_%d' % fs, [resp('4TR', -20, (5000, 10000, 14000), age=0, azimuth=a) for a in (0, 0.5, 1)])
    arr('AGE_%d' % fs, [resp('4TR', -20, age=a) for a in (0.25, 1.0)])
    nr = []
    for k in ('X2', 'B', 'C'):
        for L in (-60, -40, -20, 0):
            for f in (200, 1000, 5000):
                s = db(L) * np.sin(2 * np.pi * f * t)[:, None]
                nr.append(20 * np.log10(np.std(nr_encode(s, k, fs)[fs:]) / np.std(s[fs:])))
    arr('NRENC_%d' % fs, nr)
    print(fs, 'done', file=sys.stderr)
U1 = make_unit(1); U2 = make_unit(12345)
arr('UNIT_1', list(U1['sens']) + list(U1['cal']) + [U1['az'], U1['bias']])
arr('UNIT_12345', list(U2['sens']) + list(U2['cal']) + [U2['az'], U2['bias']])
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
