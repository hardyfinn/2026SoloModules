"""Writes test/ref_bands.h: third-octave band levels of reference renders, for the C++ agreement test.
Same measure as bandLevels() in test/render.cpp: mono (L+R)/2 in volts, Hann-windowed 8192-point
periodograms with hop 4096, averaged, summed into third-octave bands centred on 1000*2^(k/3), k=-10..13."""
import os, sys, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from presets import PRESETS
from cicada_ref import render
NAMES = ['Field Cricket', 'Katydid', 'Dog-Day Cicada', 'Pharaoh Cicada', 'Mosquito']
SECONDS = 10.0; SR = 48000

def bands(x, sr):
    n = 8192; hop = 4096; w = np.hanning(n + 1)[:-1]  # periodic Hann, same as the C++
    P = np.zeros(n // 2 + 1); cnt = 0
    for s in range(0, len(x) - n + 1, hop):
        P += np.abs(np.fft.rfft(x[s:s + n] * w))**2; cnt += 1
    P /= cnt; f = np.arange(n // 2 + 1) * sr / n
    out = []
    for k in range(-10, 14):
        c = 1000 * 2**(k / 3); lo, hi = c * 2**(-1 / 6), c * 2**(1 / 6)
        m = (f >= lo) & (f < hi); out.append(10 * np.log10(P[m].sum() + 1e-20))
    return out

if __name__ == '__main__':
    rows = []
    for nm in NAMES:
        y, _, _ = render(PRESETS[nm], SECONDS, sr=SR, seed=1)
        b = bands(y.mean(1), SR)
        rows.append('\t{"%s", {%s}},' % (nm, ', '.join('%.3f' % v for v in b)))
        print(nm, ' '.join('%.1f' % v for v in b))
    open(os.path.join(HERE, '..', '..', 'test', 'ref_bands.h'), 'w').write(
        '// Generated by tools/proto/ref_bands.py.  Do not edit.\n#pragma once\nstruct RefBands { const char* name; double db[24]; };\n'
        'static const RefBands REF_BANDS[] = {\n%s\n};\nstatic const int NUM_REF_BANDS = %d;\n' % ('\n'.join(rows), len(rows)))
