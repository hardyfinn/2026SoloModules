"""presets.py -> src/dsp/Presets.hpp (for the offline tests) and presets/Cicada/*.vcvm (for Rack).
Run from anywhere: python3 tools/proto/export_presets.py"""
import os, json, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, HERE)
from presets import PRESETS
ver = json.load(open(os.path.join(ROOT, 'plugin.json')))['version']
# Rack param ids, same order as Cicada::ParamIds
IDS = ['MECH', 'PITCH', 'PURE', 'STROKE', 'BODY', 'OPEN', 'TEMP', 'LOOSE', 'DISTANCE', 'RATE', 'CHIRP', 'GAP', 'SONG', 'LENGTH', 'VMODE']
rows = []
pdir = os.path.join(ROOT, 'presets', 'Cicada'); os.makedirs(pdir, exist_ok=True)
for f in os.listdir(pdir):
    if f.endswith('.vcvm'): os.remove(os.path.join(pdir, f))
for i, (name, p) in enumerate(PRESETS.items()):
    v = dict(p); v.setdefault('TRACK', 0)
    rows.append('\t{"%s", %d, %.4f, %.4f, %.4f, %.4f, %.4f, %.4f, %.4f, %.4f, %d, %.4f, %.4f, %.4f, %.4f, %d},' % (
        name, v['MECH'], v['PITCH'], v['PURE'], v['STROKE'], v['BODY'], v['OPEN'], v['RATE'], v['CHIRP'], v['GAP'], v['SONG'],
        v['LENGTH'], v['TEMP'], v['LOOSE'], v['DISTANCE'], v['TRACK']))
    knob = dict(MECH=2 - v['MECH'], PITCH=v['PITCH'], PURE=v['PURE'], STROKE=v['STROKE'], BODY=v['BODY'], OPEN=v['OPEN'], TEMP=v['TEMP'],
                LOOSE=v['LOOSE'], DISTANCE=v['DISTANCE'], RATE=v['RATE'], CHIRP=v['CHIRP'], GAP=v['GAP'], SONG=v['SONG'], LENGTH=v['LENGTH'],
                VMODE=0 if v['TRACK'] else 1)
    js = {"plugin": "CicadaFable", "model": "Cicada", "version": ver,
          "params": [{"value": round(float(knob[k]), 4), "id": j} for j, k in enumerate(IDS)], "data": {"individuals": 1}}
    json.dump(js, open(os.path.join(pdir, '%02d_%s.vcvm' % (i + 1, name)), 'w'), indent=1)
hpp = '''// Generated by tools/proto/export_presets.py from tools/proto/presets.py.  Do not edit.
#pragma once
namespace cicada {
struct Preset { const char* name; int mech; double pitch, pure, stroke, body, open, rate, chirp, gap; int song; double length, temp, loose, distance; int track; };
static const Preset PRESETS[] = {
%s
};
static const int NUM_PRESETS = %d;
}
''' % ('\n'.join(rows), len(rows))
open(os.path.join(ROOT, 'src', 'dsp', 'Presets.hpp'), 'w').write(hpp)
print('wrote', len(rows), 'presets')
