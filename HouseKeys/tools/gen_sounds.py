#!/usr/bin/env python3
"""Turns data/sounds.py and data/syx/*.syx into src/generated/Sounds.hpp.
   python3 tools/gen_sounds.py
Defaults for fields left out of a sound are the ones in docs/BUILD-INSTRUCTIONS.md."""
import os, runpy

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
S = runpy.run_path(os.path.join(ROOT, "data", "sounds.py"))
OUT = os.path.join(ROOT, "src", "generated", "Sounds.hpp")

WAVES = ["SINE", "SAW", "SAW 2", "SQUARE", "SQR 2", "PULSE", "PULSE 2", "TRIANG", "BELL", "BELL 2",
         "BASS", "BASS 2", "PIANO", "EL.PNO", "E.PNO2", "ORGAN", "REED", "REED 2", "BRASS", "CLAV",
         "VOICE 1", "VOICE 2", "FORMT 3", "SYNTH 1", "SYNTH 2", "GRIT 1", "GRIT 2", "GLINT 1", "GLINT 3",
         "ALIEN", "BREATH", "STEAM", "METAL", "CHIME",
         "CLICK", "THUMP", "PLINK", "PLUCK", "MALLET", "PICK 1", "SLAP", "CHIFF"]
SOURCES = ["OFF", "LFO1", "LFO2", "LFO3", "ENV1", "ENV2", "ENV3", "ENV4", "VEL", "VEL2",
           "KBD", "KBD2", "WHEEL", "PRESS"]
LFOW = ["TRI", "SAW", "SQR", "NOI"]
PDW = ["SAW", "SQUARE", "PULSE", "DSINE", "SAWPULSE", "RES1", "RES2", "RES3"]
POLYMODEL = ["JUNO", "JUP", "JX", "P800"]
POLYW2 = ["saw", "pulse", "tri", "sq"]
GENS = ["strings", "piano", "choir", "brass", "orchhit", "upright", "vibes", "chord"]


def f(x):
    s = repr(float(x))
    return s + "f"


def arr(xs, fn=f):
    return "{" + ", ".join(fn(x) for x in xs) + "}"


def cstr(s):
    return '"' + s.replace('"', '\\"') + '"'


lines = ["// Generated by tools/gen_sounds.py from data/sounds.py and data/syx. Do not edit.",
         "#pragma once", "#include \"../dsp/SoundTypes.hpp\"", "", "namespace hk {", ""]

# ---------------- FM
fm = []
for name, fn, slot, chip in S["FM"]:
    d = open(os.path.join(ROOT, "data", "syx", fn), "rb").read()
    assert len(d) == 4104 and d[:6] == bytes([0xF0, 0x43, 0x00, 0x04, 0x20, 0x00])
    v = d[6 + 128 * slot: 6 + 128 * slot + 128]
    fm.append("\t{" + cstr(name) + ", " + ("true" if chip == "OPZ" else "false") + ", {" +
              ", ".join(str(b) for b in v) + "}}")
lines.append("static const FmSound FM_SOUNDS[%d] = {\n%s\n};\n" % (len(fm), ",\n".join(fm)))

# ---------------- POLY
def env4(e, gate_default=False):
    if e == "gate":
        return [0.002, 0.0, 1.0, 0.006], True
    return list(e), False


poly = []
for p in S["POLY"]:
    lfo = p.get("lfo", {})
    aenv, agate = env4(p.get("aenv", [0.002, 0.0, 1.0, 0.006]))
    fenv, _ = env4(p.get("fenv", [0.002, 0.0, 1.0, 0.006]))
    vals = [
        cstr(p["n"]), str(POLYMODEL.index(p["model"])), str(p.get("oct", 0)),
        f(p.get("saw", 0)), f(p.get("pulse", 0)), f(p.get("tri", 0)), f(p.get("sub", 0)), f(p.get("noise", 0)),
        f(p.get("pw", 0.5)), f(p.get("pwm", 0)),
        f(p.get("lvl2", 0)), str(POLYW2.index(p.get("wave2", "saw"))), str(p.get("oct2", 0)),
        f(p.get("semi2", 0)), f(p.get("fine2", 0)), str(p.get("sync", 0)), f(p.get("sweep2", 0)),
        str(p.get("hpf", 1 if p["model"] == "JUNO" else 0)), f(p.get("cut", 1000)), f(p.get("res", 0)),
        f(p.get("env", 0)), f(p.get("kbd", 0)), f(p.get("velcut", 0)), str(p.get("poles", 4)),
        arr(fenv), arr(aenv), "true" if agate else "false",
        f(lfo.get("rate", 0)), f(lfo.get("delay", 0)), f(lfo.get("pitch", 0)),
        f(p.get("vel", 0)), "true" if p.get("mono", False) else "false", f(p.get("glide", 0)),
        str(p.get("chorus", 0)),
    ]
    poly.append("\t{" + ", ".join(vals) + "}")
lines.append("static const PolySound POLY_SOUNDS[%d] = {\n%s\n};\n" % (len(poly), ",\n".join(poly)))

# ---------------- PD
def pdline(w, dcw, amp):
    if amp == "gate":
        a, g = [0.002, 0.0, 1.0, 0.006], True
    else:
        a, g = list(amp), False
    ws = [PDW.index(x) for x in w]
    if len(ws) == 1:
        ws = ws * 2
        nw = 1
    else:
        nw = 2
    return "{" + arr(ws, str) + ", %d, " % nw + arr(dcw) + ", " + arr(a) + ", " + ("true" if g else "false") + "}"


pd = []
for p in S["PD"]:
    l1 = pdline(p["w"], p["dcw"], p["amp"])
    l2 = pdline(p.get("w2", p["w"]), p.get("dcw2", p["dcw"]), p.get("amp2", p["amp"]))
    mode = {"1": 0, "1+1'": 1, "1+2'": 2}[p["mode"]]
    vib = p.get("vib", {})
    trem = p.get("trem", {})
    det = p.get("det", (0, 0, 0))
    vals = [cstr(p["n"]), str(p.get("oct", 0)), str(mode), l1, l2, f(p.get("lvl2", 1.0)),
            arr(det), str(p.get("ring", 0)),
            f(vib.get("rate", 0)), f(vib.get("delay", 0)), f(vib.get("cents", 0)),
            f(trem.get("rate", 0)), f(trem.get("depth", 0)),
            f(p.get("dcwkey", 0)), str(p.get("chorus", 0)), f(p.get("vel", 0)),
            "true" if p.get("mono", False) else "false", f(p.get("glide", 0))]
    pd.append("\t{" + ", ".join(vals) + "}")
lines.append("static const PdSound PD_SOUNDS[%d] = {\n%s\n};\n" % (len(pd), ",\n".join(pd)))

# ---------------- WAVE
wv = []
for p in S["WAVE"]:
    oscs = []
    om = p.get("om", {})
    for i, o in enumerate(p["o"]):
        mods = om.get(i, {})
        pm = mods.get("pm", ("OFF", 0))
        am = mods.get("am", ("OFF", 0))
        if o is None:
            oscs.append("{false, 0, 0, 0, 0, 0, 0, 0, 0, 0}")
        else:
            w, oc, se, fi, lv = o
            oscs.append("{true, %d, %d, %d, %d, %d, %d, %d, %d, %d}" % (
                WAVES.index(w), oc, se, fi, lv, SOURCES.index(pm[0]), pm[1], SOURCES.index(am[0]), am[1]))
    fl = p["f"]
    m1 = fl.get("m1", ("OFF", 0))
    m2 = fl.get("m2", ("OFF", 0))
    envs = []
    for k in ("e1", "e2", "e3", "e4"):
        e = p.get(k, [0] * 10 if k != "e4" else [63, 63, 63, 0, 0, 0, 10, 0, 0, 0])
        assert len(e) == 10
        envs.append(arr(e, str))
    lfos = []
    for k in ("l1", "l2", "l3"):
        l = p.get(k, [0, "TRI", 0, 0, 0, "OFF"])
        lfos.append("{%d, %d, %d, %d, %d, %d}" % (l[0], LFOW.index(l[1]), l[2], l[3], l[4], SOURCES.index(l[5])))
    vals = [cstr(p["n"]), "{" + ", ".join(oscs) + "}",
            str(fl.get("cut", 127)), str(fl.get("res", 0)), str(fl.get("kbd", 0)),
            str(SOURCES.index(m1[0])), str(m1[1]), str(SOURCES.index(m2[0])), str(m2[1]),
            "{" + ", ".join(envs) + "}", "{" + ", ".join(lfos) + "}",
            str(p.get("pan", 8)), str(p.get("sync", 0)), str(p.get("am", 0)),
            "true" if p.get("mono", False) else "false", str(p.get("glide", 0))]
    wv.append("\t{" + ", ".join(vals) + "}")
lines.append("static const WaveSound WAVE_SOUNDS[%d] = {\n%s\n};\n" % (len(wv), ",\n".join(wv)))

# ---------------- SAMPLER
sm = []
for p in S["SAMPLER"]:
    g, gp = p["gen"]
    prm = [0.0] * 6
    notes = []
    if g == "strings":
        prm[:4] = [gp.get("players", 12), gp.get("bright", 0.6), gp.get("marcato", 0.0), 1.0 if gp.get("body") == "cello" else 0.0]
    elif g == "piano":
        prm[:2] = [gp.get("hardness", 0.6), gp.get("strings", 3)]
    elif g == "choir":
        prm[:1] = [gp.get("singers", 10)]
    elif g == "brass":
        prm[:2] = [gp.get("players", 4), gp.get("bright", 0.6)]
    elif g == "vibes":
        prm[:1] = [gp.get("motor", 0.0)]
    elif g == "chord":
        notes = gp["notes"]
        prm[:3] = [1.0, gp.get("cut", 1800), gp.get("res", 0.3)]
    z = p["zones"]
    assert len(z) <= 8 and len(notes) <= 6
    assert len(z) * p["len"] * p["sr"] <= 131072 + 1e-6, p["n"]
    loop = p["loop"]
    vals = [cstr(p["n"]), str(GENS.index(g)), arr(prm), arr(notes + [0] * (6 - len(notes)), str), str(len(notes)),
            arr(z + [0] * (8 - len(z)), str), str(len(z)), f(p["sr"]), f(p["len"]),
            "true" if loop else "false", arr(loop if loop else (0, 0, 0)),
            f(p.get("det", 0)), f(p.get("mix", 0)), f(p["cut"]), f(p.get("res", 0)), f(p.get("kbd", 0)),
            f(p.get("env", 0)), arr(p["fenv"]), arr(p["aenv"]), f(p.get("vel", 0)), f(p.get("velcut", 0))]
    sm.append("\t{" + ", ".join(vals) + "}")
lines.append("static const SmpSound SMP_SOUNDS[%d] = {\n%s\n};\n" % (len(sm), ",\n".join(sm)))

lines.append("static const char* const WAVE_NAMES[%d] = {%s};" % (len(WAVES), ", ".join(cstr(w) for w in WAVES)))
lines.append("static const int NUM_WAVES = %d;" % len(WAVES))
lines.append("")
lines.append("} // namespace hk")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, len(fm), len(poly), len(pd), len(wv), len(sm))
