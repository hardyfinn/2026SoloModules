"""tools/proto/rider_kit.json -> src/dsp/RiderKitData.hpp (the fitted kit, and the band filters, as C++ tables).   python3 tools/rider_kit_to_h.py"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, 'proto'))
import rider_kit_ref as K
D = K.D; f = lambda x: repr(float(x))
o = ['// generated by tools/rider_kit_to_h.py from tools/proto/rider_kit.json; do not edit', '#pragma once', 'namespace riderkit {',
     'static const int NB = %d, NRATES = %d, NCLICK = %d, NTAUS = %d, NTAPS = %d, NVOICES = %d, NSWEEP = %d;' % (K.NB, len(K.RATES), len(K.CLICK), len(K.TAUS), len(K.TAPS), len(K.VOICES), len(D['sweep']['lx'])),
     'static const double EDGES[NB + 1] = {%s};' % ','.join(f(x) for x in K.EDGES),
     'static const double RATES[NRATES] = {%s};   // dB per second of power' % ','.join(f(x) for x in K.RATES),
     'static const double CLICK[NCLICK] = {%s};' % ','.join(f(x) for x in K.CLICK),
     'static const double TAUS[NTAUS] = {%s};   // seconds' % ','.join(f(x) for x in K.TAUS),
     'static const int TAP_DELAY[NTAPS] = {%s};' % ','.join(str(int(d)) for d, g in K.TAPS),
     'static const double TAP_GAIN[NTAPS] = {%s};' % ','.join(f(g) for d, g in K.TAPS),
     '// two biquads per band (b0 b1 b2 a1 a2, a0 = 1), 48 kHz: scipy.signal.butter(2, [lo, hi], "band")',
     'static const double SOS[NB][2][5] = {%s};' % ','.join('{' + ','.join('{%s}' % ','.join(f(K.SOS[i][s][c]) for c in (0, 1, 2, 4, 5)) for s in range(2)) + '}' for i in range(K.NB)),
     '// the power of unit white noise after each band filter',
     'static const double BANDPOWER[NB] = {%s};' % ','.join(f(x) for x in K.BP),
     'struct Partial { double f, a, r; };   // Hz, amplitude at the reference stroke, dB per second',
     'struct WashC { short band, rate, tau; double c; };   // tau -1: plain decay',
     'struct Voice { const char* name; int family, mix, tuned, closes; double pan; int npart; const Partial* part; int nwash; const WashC* wash;',
     '               double click[NB][NCLICK]; double gain[NB], cgain[NB]; int nl; double lx[5]; double ltail[5][NB]; double lclick[5][NB]; };']
for vi, name in enumerate(K.VOICES):
    if name == 'brush-sweep': continue
    d = D['voices'][name]
    o.append('static const Partial part%d[] = {%s};' % (vi, ','.join('{%s,%s,%s}' % (f(a), f(b), f(c)) for a, b, c in d['part']) or '{0,0,1}'))
    w = [(i, ri, ti, c) for i in range(K.NB) for (ri, ti, c) in d['wash'][i]]
    o.append('static const WashC wash%d[] = {%s};' % (vi, ','.join('{%d,%d,%d,%s}' % (i, ri, ti, f(c)) for i, ri, ti, c in w) or '{0,0,-1,0}'))
o.append('static const Voice VOICES[NVOICES] = {')
for vi, name in enumerate(K.VOICES):
    head = '"%s",%d,%d,%d,%d,%s' % (name, K.FAMILY[vi], K.MIX[vi], K.TUNED[vi], K.CLOSES[vi], f(K.PAN[vi]))
    if name == 'brush-sweep': o.append('  {%s,0,nullptr,0,nullptr,{},{},{},0,{},{},{}},' % head); continue
    d = D['voices'][name]; nw = sum(len(x) for x in d['wash']); nl = len(d['lx']); assert nl <= 5
    rows = lambda T: ','.join('{' + ','.join(f(x) for x in r) + '}' for r in T)
    o.append('  {%s,%d,part%d,%d,wash%d,{%s},{%s},{%s},%d,{%s},{%s},{%s}},' % (head, len(d['part']), vi, nw, vi, rows(d['click']), ','.join(f(x) for x in d['gain']), ','.join(f(x) for x in d['cgain']),
             nl, ','.join(f(x) for x in d['lx']), rows(d['ltail']), rows(d['lclick'])))
o.append('};')
s = D['sweep']
o.append('static const double SWEEP_LX[NSWEEP] = {%s};' % ','.join(f(x) for x in s['lx']))
o.append('static const double SWEEP_BANDS[NSWEEP][NB] = {%s};' % ','.join('{' + ','.join(f(x) for x in r) + '}' for r in s['bands']))
o.append('}')
open(os.path.join(HERE, '..', 'src', 'dsp', 'RiderKitData.hpp'), 'w').write('\n'.join(o) + '\n'); print('wrote src/dsp/RiderKitData.hpp')
