"""test/walker_golden.json -> test/walker_golden.h (so the C++ test needs no JSON parser).   python3 tools/walker_golden_to_h.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); T = os.path.join(HERE, '..', 'test')
G = json.load(open(os.path.join(T, 'walker_golden.json')))
KEYS = ['feel', 'activity', 'register', 'roam', 'out', 'repeat', 'loose', 'timing', 'weight', 'slop', 'pitch', 'ahead', 'swing']
DEF = dict(feel=0, activity=0.5, register=40.0, roam=0.5, out=0.2, repeat=0.7, loose=1.0, timing=1.0, weight=1.0, slop=1.0, pitch=1.0, ahead=0.5, swing=0.0)
assert all(c['fields'] == ['t', 'pitch', 'vel', 'dur', 'dead', 'scoop', 'cents', 'vib', 'string', 'fret', 'stopped', 'beat'] for c in G)
f = lambda x: repr(float(x))
o = ['// generated by tools/walker_golden_to_h.py from walker_golden.json; do not edit', '#pragma once',
     'struct WGChord { double beat; int root, q; };',
     'struct WGNote { double t; int pitch; double vel, dur; int dead; double scoop, cents, vib; int string, fret, stopped; double beat; };',
     'struct WGCase { const char* name; int nchart; const WGChord* chart; double total; double bpm; int nbars; int seed; bool blind; double prm[%d]; int nnotes; const WGNote* notes; };' % len(KEYS)]
for i, c in enumerate(G):
    o.append('static const WGChord wgc%d[] = {%s};' % (i, ','.join('{%s,%d,%d}' % (f(b), r, q) for b, r, q in c['chart'])))
    o.append('static const WGNote wgn%d[] = {%s};' % (i, ','.join('{%s,%d,%s,%s,%d,%s,%s,%s,%d,%d,%d,%s}' % (f(n[0]), n[1], f(n[2]), f(n[3]), n[4], f(n[5]), f(n[6]), f(n[7]), n[8], n[9], n[10], f(n[11])) for n in c['notes'])))
o.append('static const WGCase WGOLDEN[] = {')
for i, c in enumerate(G):
    pr = dict(DEF); pr.update(c['params'])
    o.append('  {"%s",%d,wgc%d,%s,%s,%d,%d,%s,{%s},%d,wgn%d},' % (c['name'], len(c['chart']), i, f(c['total_beats']), f(c['bpm']), c['nbars'], c['seed'],
             'true' if c['blind'] else 'false', ','.join(f(pr[k]) for k in KEYS), len(c['notes']), i))
o.append('};'); o.append('static const int NUM_WGOLDEN = %d;' % len(G))
open(os.path.join(T, 'walker_golden.h'), 'w').write('\n'.join(o) + '\n'); print('wrote test/walker_golden.h', len(G), 'cases')
