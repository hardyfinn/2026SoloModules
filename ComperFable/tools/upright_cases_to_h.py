"""test/upright_cases.json -> test/upright_cases.h (notes, tones and seeds of the sound check).   python3 tools/upright_cases_to_h.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); T = os.path.join(HERE, '..', 'test')
C = json.load(open(os.path.join(T, 'upright_cases.json')))
TK = ['pluck', 'bright', 'sustain', 'growl', 'body', 'pickup', 'age', 'thump', 'attack']
TD = dict(pluck=0.17, bright=0.5, sustain=0.5, growl=0.35, body=0.6, pickup=0.25, age=0.3, thump=0.5, attack=1.0)
f = lambda x: repr(float(x))
o = ['// generated by tools/upright_cases_to_h.py from upright_cases.json; do not edit', '#pragma once',
     'struct UNote { double t; int pitch; double vel, dur; int dead; double scoop, cents, vib; int stopped, string, fret; };',
     'struct UCase { const char* name; double tone[9]; int seed; double total; int nnotes; const UNote* notes; };']
for i, c in enumerate(C):
    o.append('static const UNote un%d[] = {%s};' % (i, ','.join('{%s,%d,%s,%s,%d,%s,%s,%s,%d,%d,%d}' % (f(n['t']), n['pitch'], f(n['vel']), f(n['dur']), int(n['dead']), f(n['scoop']), f(n['cents']), f(n['vib']), int(n['stopped']), n['string'], n['fret']) for n in c['notes'])))
o.append('static const UCase UCASES[] = {')
for i, c in enumerate(C):
    t = dict(TD); t.update(c['tone'])
    o.append('  {"%s",{%s},%d,%s,%d,un%d},' % (c['name'], ','.join(f(t[k]) for k in TK), c['seed'], f(c['total']), len(c['notes']), i))
o.append('};'); o.append('static const int NUM_UCASES = %d;' % len(C))
open(os.path.join(T, 'upright_cases.h'), 'w').write('\n'.join(o) + '\n'); print('wrote test/upright_cases.h', len(C), 'cases')
