"""rider_presets.py -> presets/Rider/*.vcvm (Rack presets) and test/rider_presets.h (for the C++ renders).
   python3 tools/proto/export_rider_presets.py"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import rider_presets as RPS
ROOT = os.path.join(HERE, '..', '..')
# parameter ids of the Rider module (src/Rider.cpp ParamIds order)
PARAMS = ['FEEL', 'ENERGY', 'COMP', 'LISTEN', 'FILLS', 'FEATHER', 'REPEAT', 'BAND', 'SEED', 'NEW', 'LOOSE', 'AHEAD',
          'RIDE', 'HATS', 'SNARE', 'KICK', 'TOMS', 'TUNE', 'DECAY', 'BRIGHT', 'WIDTH', 'AGE', 'LEVEL']
DEF = dict(FEEL=0, ENERGY=0.5, COMP=0.5, LISTEN=1.0, FILLS=0.5, FEATHER=0.5, REPEAT=0.6, BAND=0.0, SEED=1, NEW=0, LOOSE=1.0, AHEAD=0.5,
           RIDE=1.0, HATS=1.0, SNARE=1.0, KICK=1.0, TOMS=1.0, TUNE=0.5, DECAY=0.5, BRIGHT=0.5, WIDTH=1.0, AGE=0.0, LEVEL=1.0)
def values(player, kit):
    v = dict(DEF)
    for k, x in player.items(): v[k.upper()] = (x + 1) if k == 'feel' else x      # panel FEEL: 0 FOLLOW, 1.. SWING BOSSA BALLAD SOUL HOUSE
    for k, x in kit.items(): v[k.upper()] = x
    return v
d = os.path.join(ROOT, 'presets', 'Rider'); os.makedirs(d, exist_ok=True)
for f in os.listdir(d):
    if f.endswith('.vcvm'): os.remove(os.path.join(d, f))
for name, player, kit in RPS.PRESETS:
    v = values(player, kit)
    pre = dict(plugin='ComperFable', model='Rider', version='2.2.0', params=[dict(id=i, value=float(v[p])) for i, p in enumerate(PARAMS)], data=dict(ppb=0, chorusBars=12))
    json.dump(pre, open(os.path.join(d, name + '.vcvm'), 'w'), indent=1)
o = ['// generated by tools/proto/export_rider_presets.py; do not edit', '#pragma once',
     'struct RPreset { const char* name; double v[%d]; };   // %s' % (len(PARAMS), ' '.join(PARAMS)), 'static const RPreset RPRESETS[] = {']
for name, player, kit in RPS.PRESETS:
    v = values(player, kit); o.append('  {"%s",{%s}},' % (name, ','.join(repr(float(v[p])) for p in PARAMS)))
o.append('};'); o.append('static const int NUM_RPRESETS = %d;' % len(RPS.PRESETS))
open(os.path.join(ROOT, 'test', 'rider_presets.h'), 'w').write('\n'.join(o) + '\n')
print('wrote', len(RPS.PRESETS), 'presets')
