"""walker_presets.py -> presets/Walker/*.vcvm (Rack presets) and test/walker_presets.h (for the C++ renders).
   python3 tools/proto/export_walker_presets.py"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import walker_presets as WP
ROOT = os.path.join(HERE, '..', '..')
# parameter ids of the Walker module (src/Walker.cpp ParamIds order)
PARAMS = ['FEEL', 'ACTIVITY', 'REGISTER', 'ROAM', 'OUT', 'REPEAT', 'SEED', 'NEW', 'LOOSE', 'AHEAD', 'TIMING', 'WEIGHT', 'SLOP', 'PITCH',
          'ATTACK', 'PLUCK', 'BRIGHT', 'SUSTAIN', 'GROWL', 'BODY', 'PICKUP', 'THUMP', 'AGE', 'LEVEL']
DEF = dict(FEEL=0, ACTIVITY=0.5, REGISTER=40.0, ROAM=0.5, OUT=0.2, REPEAT=0.7, SEED=1, NEW=0, LOOSE=1.0, AHEAD=0.5, TIMING=1.0, WEIGHT=1.0,
           SLOP=1.0, PITCH=1.0, ATTACK=1.0, PLUCK=0.17, BRIGHT=0.5, SUSTAIN=0.5, GROWL=0.35, BODY=0.6, PICKUP=0.25, THUMP=0.5, AGE=0.3, LEVEL=1.0)
LINE = dict(feel='FEEL', activity='ACTIVITY', register='REGISTER', roam='ROAM', out='OUT', repeat='REPEAT', loose='LOOSE', ahead='AHEAD',
            timing='TIMING', weight='WEIGHT', slop='SLOP', pitch='PITCH')
TONE = dict(attack='ATTACK', pluck='PLUCK', bright='BRIGHT', sustain='SUSTAIN', growl='GROWL', body='BODY', pickup='PICKUP', thump='THUMP', age='AGE')
def values(line, tone):
    v = dict(DEF)
    for k, x in line.items(): v[LINE[k]] = (x + 1) if k == 'feel' else x      # panel FEEL: 0 FOLLOW, 1.. WALK..
    for k, x in tone.items(): v[TONE[k]] = x
    return v
d = os.path.join(ROOT, 'presets', 'Walker'); os.makedirs(d, exist_ok=True)
for f in os.listdir(d):
    if f.endswith('.vcvm'): os.remove(os.path.join(d, f))
for name, line, tone in WP.PRESETS:
    v = values(line, tone)
    pre = dict(plugin='ComperFable', model='Walker', version='2.1.0', params=[dict(id=i, value=float(v[p])) for i, p in enumerate(PARAMS)],
               data=dict(ppb=0, tuneBars=0, voctSlides=True))
    json.dump(pre, open(os.path.join(d, name + '.vcvm'), 'w'), indent=1)
o = ['// generated by tools/proto/export_walker_presets.py; do not edit', '#pragma once',
     'struct WPreset { const char* name; double v[%d]; };' % len(PARAMS), 'static const WPreset WPRESETS[] = {']
for name, line, tone in WP.PRESETS:
    v = values(line, tone); o.append('  {"%s",{%s}},' % (name, ','.join(repr(float(v[p])) for p in PARAMS)))
o.append('};'); o.append('static const int NUM_WPRESETS = %d;' % len(WP.PRESETS))
open(os.path.join(ROOT, 'test', 'walker_presets.h'), 'w').write('\n'.join(o) + '\n')
print('wrote', len(WP.PRESETS), 'presets')
