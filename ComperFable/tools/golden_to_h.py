"""test/golden.json + test/detect.json -> test/golden.h (so the C++ test needs no JSON parser).
   python3 tools/golden_to_h.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); T = os.path.join(HERE, '..', 'test')
G = json.load(open(os.path.join(T, 'golden.json'))); D = json.load(open(os.path.join(T, 'detect.json')))
KEYS = ['style', 'spread', 'register', 'voices', 'lead', 'out', 'roots', 'groove', 'density', 'swing', 'repeat', 'push',
        'loose', 'timing', 'roll', 'weight', 'slop', 'pedal', 'listen']
DEF = dict(style=1, spread=0.25, register=69.0, voices=5, lead=1.0, out=0.0, roots=0, groove=0, density=0.5, swing=0.0,
           repeat=0.6, push=0.85, loose=1.0, timing=1.0, roll=1.0, weight=1.0, slop=1.0, pedal=0.0, listen=0.0)
o = ['// generated by tools/golden_to_h.py from golden.json and detect.json; do not edit', '#pragma once',
     'struct GChord { double beat; int root, q; };', 'struct GNote { double on, off; int pitch, vel; };',
     'struct GSolo { double on, off; int pitch; };', 'struct GPedal { double t, v; };',
     'struct GCase { const char* name; int nchart; const GChord* chart; double total; double bpm; int nbars; int seed; bool external;',
     '  int nsolo; const GSolo* solo; double prm[%d]; int nnotes; const GNote* notes; int npedal; const GPedal* pedal; };' % len(KEYS)]
f = lambda x: repr(float(x))
for i, c in enumerate(G):
    o.append('static const GChord gc%d[] = {%s};' % (i, ','.join('{%s,%d,%d}' % (f(b), r, q) for b, r, q in c['chart'])))
    o.append('static const GSolo gs%d[] = {%s};' % (i, ','.join('{%s,%s,%d}' % (f(a), f(b), p) for a, b, p in c['solo']) or '{0,0,0}'))
    o.append('static const GNote gn%d[] = {%s};' % (i, ','.join('{%s,%s,%d,%d}' % (f(a), f(b), p, v) for a, b, p, v in c['notes'])))
    o.append('static const GPedal gp%d[] = {%s};' % (i, ','.join('{%s,%s}' % (f(t), f(v)) for t, v in c['pedal']) or '{0,0}'))
o.append('static const GCase GOLDEN[] = {')
for i, c in enumerate(G):
    pr = dict(DEF); pr.update(c['params'])
    o.append('  {"%s",%d,gc%d,%s,%s,%d,%d,%s,%d,gs%d,{%s},%d,gn%d,%d,gp%d},' % (
        c['name'], len(c['chart']), i, f(c['total_beats']), f(c['bpm']), c['nbars'], c['seed'], 'true' if c['external'] else 'false',
        len(c['solo']), i, ','.join(f(pr[k]) for k in KEYS), len(c['notes']), i, len(c['pedal']), i))
o.append('};')
o.append('static const int NUM_GOLDEN = %d;' % len(G))
o.append('struct GDetect { int n; int notes[8]; int lastq; int root, q; };')
o.append('static const GDetect DETECT[] = {%s};' % ','.join('{%d,{%s},%d,%d,%d}' % (len(ns), ','.join(map(str, ns)), lq, d[0], d[1]) for ns, lq, d in D))
o.append('static const int NUM_DETECT = %d;' % len(D))
open(os.path.join(T, 'golden.h'), 'w').write('\n'.join(o) + '\n')
print('wrote test/golden.h', len(G), 'cases', len(D), 'detect')
