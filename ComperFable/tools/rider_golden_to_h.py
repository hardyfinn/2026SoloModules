"""test/rider_golden.json -> test/rider_golden.h, test/rider_kit_cases.json -> test/rider_kit_cases.h (so the C++ tests need no JSON parser).
   python3 tools/rider_golden_to_h.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); T = os.path.join(HERE, '..', 'test')
f = lambda x: repr(float(x))
G = json.load(open(os.path.join(T, 'rider_golden.json')))
KEYS = ['feel', 'energy', 'comp', 'listen', 'fills', 'feather', 'repeat', 'loose', 'ahead', 'swing']
DEF = dict(feel=0, energy=0.5, comp=0.5, listen=1.0, fills=0.5, feather=0.5, repeat=0.6, loose=1.0, ahead=0.5, swing=0.0)
o = ['// generated by tools/rider_golden_to_h.py from rider_golden.json; do not edit', '#pragma once',
     'struct RGBar { int hasPiano, slots; int kind[16]; double slotBeat[16]; int push[16]; int nbass; double bassOff[8]; int forceFill; double energy; };   // energy < 0: use the parameter',
     'struct RGNote { double t; int voice, vel; double dur, beat; };',
     'struct RGCase { const char* name; double bpm; int chorusBars, seed; double prm[%d]; int nbars; const RGBar* bars; int nnotes; const RGNote* notes; };   // prm: %s' % (len(KEYS), ' '.join(KEYS))]
for i, c in enumerate(G):
    bars = []
    for bi, b in enumerate(c['bars']):
        bo = (b['bass_off'] + [0.0] * 8)[:8]; assert len(b['bass_off']) <= 8
        en = c['energy'][bi] if c['energy'] else -1.0
        bars.append('{%d,%d,{%s},{%s},{%s},%d,{%s},%d,%s}' % (b['has_piano'], b['slots'], ','.join(str(k) for k in b['kind']), ','.join(f(x) for x in b['slot_beat']),
                    ','.join(str(x) for x in b['push']), len(b['bass_off']), ','.join(f(x) for x in bo), b['force_fill'], f(en)))
    o.append('static const RGBar rgb%d[] = {%s};' % (i, ','.join(bars)))
    o.append('static const RGNote rgn%d[] = {%s};' % (i, ','.join('{%s,%d,%d,%s,%s}' % (f(n[0]), n[1], n[2], f(n[3]), f(n[4])) for n in c['notes'])))
o.append('static const RGCase RGOLDEN[] = {')
for i, c in enumerate(G):
    pr = dict(DEF); pr.update(c['params'])
    o.append('  {"%s",%s,%d,%d,{%s},%d,rgb%d,%d,rgn%d},' % (c['name'], f(c['bpm']), c['chorus_bars'], c['seed'], ','.join(f(pr[k]) for k in KEYS), len(c['bars']), i, len(c['notes']), i))
o.append('};'); o.append('static const int NUM_RGOLDEN = %d;' % len(G))
open(os.path.join(T, 'rider_golden.h'), 'w').write('\n'.join(o) + '\n'); print('wrote test/rider_golden.h', len(G), 'cases')

K = json.load(open(os.path.join(T, 'rider_kit_cases.json')))
KK = ['level', 'tune', 'decay', 'bright', 'width', 'age']; KD = dict(level=1.0, tune=0.5, decay=0.5, bright=0.5, width=1.0, age=0.0)
o = ['// generated by tools/rider_golden_to_h.py from rider_kit_cases.json; do not edit', '#pragma once',
     'struct RKStroke { double t; int voice, vel; };', 'struct RKSweep { double t, dur; int vel; };', 'struct RKWin { double a, b; };',
     'struct RKCase { const char* name; int seed; double dur; double kit[%d]; double mix[5]; int nstrokes; const RKStroke* strokes; int nsweeps; const RKSweep* sweeps; int nwins; const RKWin* wins; const float* cells; double peak; };' % len(KK),
     '// kit: %s.  cells: [channel 2][band 26][window nwins], dB' % ' '.join(KK)]
for i, c in enumerate(K):
    o.append('static const RKStroke rks%d[] = {%s};' % (i, ','.join('{%s,%d,%d}' % (f(t), v, vel) for t, v, vel in c['strokes']) or '{0,0,0}'))
    o.append('static const RKSweep rkw%d[] = {%s};' % (i, ','.join('{%s,%s,%d}' % (f(t), f(d), vel) for t, d, vel in c['sweeps']) or '{0,0,0}'))
    o.append('static const RKWin rkn%d[] = {%s};' % (i, ','.join('{%s,%s}' % (f(a), f(b)) for a, b in c['wins'])))
    o.append('static const float rkc%d[] = {%s};' % (i, ','.join('%.3f' % x for ch in c['cells'] for row in ch for x in row)))
o.append('static const RKCase RKCASES[] = {')
for i, c in enumerate(K):
    kp = dict(KD); kp.update({k: v for k, v in c['kit'].items() if k != 'mix'}); mix = c['kit'].get('mix', [1.0] * 5)
    o.append('  {"%s",%d,%s,{%s},{%s},%d,rks%d,%d,rkw%d,%d,rkn%d,rkc%d,%s},' % (c['name'], c['seed'], f(c['dur']), ','.join(f(kp[k]) for k in KK), ','.join(f(x) for x in mix),
             len(c['strokes']), i, len(c['sweeps']), i, len(c['wins']), i, i, f(c['peak'])))
o.append('};'); o.append('static const int NUM_RKCASES = %d;' % len(K))
open(os.path.join(T, 'rider_kit_cases.h'), 'w').write('\n'.join(o) + '\n'); print('wrote test/rider_kit_cases.h', len(K), 'cases')
